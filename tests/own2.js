const { chromium } = require('playwright');
const OUT = process.argv[2];
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext();
  const errors = [];
  const watch = (pg, n) => pg.on('pageerror', e => errors.push(n + ': ' + e.message));
  const host = await ctx.newPage(); watch(host, 'host');
  await host.setViewportSize({ width: 1600, height: 900 });
  await host.goto('http://localhost:8765/index.html?lokal=1');
  await host.evaluate(() => localStorage.clear()); await host.reload();
  await host.click('[data-count="3"]');
  await host.fill('#pname0', 'Søren'); await host.fill('#pname1', 'Materikles'); await host.fill('#pname2', 'Mamasita');
  await host.click('[data-avopen="1"]'); await host.click('[data-avpanel="1"] [data-av-icon="olive"]');
  await host.click('[data-avopen="2"]'); await host.click('[data-avpanel="2"] [data-av-icon="barn-owl"]');
  await host.click('#setupForm button[type=submit]'); await host.waitForTimeout(300);
  const code = (await host.textContent('.join-code')).trim();
  const phone = await ctx.newPage(); watch(phone, 'phone');
  await phone.setViewportSize({ width: 390, height: 844 });
  await phone.goto(`http://localhost:8765/telefon.html?rum=${code}&lokal=1&cid=o1`);
  await phone.waitForSelector('[data-claim]'); await phone.click('[data-claim="1"]');
  await host.click('#lobbyStart'); await host.waitForTimeout(500);
  await host.evaluate(() => {
    const own = { 3: 0, 6: 1, 14: 2, 15: 2, 17: 2, 19: 0, 21: 0, 22: 0, 25: 1, 18: 1, 31: 1, 30: 1, 11: 2 };
    Object.entries(own).forEach(([i, o]) => state.props[i].owner = o);
    state.props[19].level = 2; state.props[21].level = 3; state.props[22].level = 4; state.props[31].level = 5; state.props[30].level = 1; state.props[15].level = 2;
    state.props[11].mortgaged = true;
    broadcast();
  });
  await host.waitForTimeout(700);
  await host.evaluate(() => { state.players[1].money -= 240; state.players[0].money += 240; broadcast(); });
  await host.waitForTimeout(380);
  await host.screenshot({ path: OUT + '/o_host.png' });
  await phone.waitForTimeout(50);
  await phone.screenshot({ path: OUT + '/o_phone.png' });
  await host.evaluate(() => { const i = 21; state.prompt = null; state.props[i].level = 3; });
  await phone.click('#tabs [data-tab="props"]'); await phone.waitForTimeout(300);
  await phone.screenshot({ path: OUT + '/o_props.png' });
  console.log(JSON.stringify(errors));
  await browser.close();
})();
